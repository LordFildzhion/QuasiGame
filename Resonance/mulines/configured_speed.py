"""Configurable Resonance/SPEED EMG streaming pipeline.

The UTF-8 INI file is the single user-facing source of truth. Source stream
binding is regenerated by Update_SPEED_Profile.ps1 before launching SPEED.
Changes to signal processing require re-Prepare after restarting SPEED.
"""
from __future__ import annotations

import configparser
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from adaptive_normalizer import (
    AdaptiveEMGInterpreter,
    ChannelQualityProfile,
    RollingNormalizerConfig,
    load_baseline_report,
)
from emg_interpreter import FilterConfig
from final_emg_interpreter import FinalEMGInterpreter
from noise_quality import MainsCancellerConfig, SignalQualityConfig
from contraction_detector import ContractionDetectorSettings, ContractionEventDetector


@dataclass(frozen=True)
class SpeedSettings:
    source_service: str
    source_stream: str
    sampling_rate_hz: float
    input_units: str
    left_channel: int                 # 1-based; zero disables channel
    right_channel: int
    left_sensor_name: str             # label for readable diagnostics
    right_sensor_name: str
    threshold_mode: str               # baseline | manual
    left_threshold_uv: float
    right_threshold_uv: float
    low_hz: float
    high_hz: float
    notch_hz: float                   # zero disables notch
    notch_q: float
    filter_order: int
    rms_window_ms: float
    attack_ms: float
    release_ms: float
    rolling_window_seconds: float
    bridge_enabled: bool
    bridge_host: str
    bridge_port: int
    event_detector: ContractionDetectorSettings
    @property
    def source_indices(self) -> tuple[int | None, int | None]:
        return (self.left_channel - 1 if self.left_channel else None,
                self.right_channel - 1 if self.right_channel else None)

    @property
    def unit_scale(self) -> float:
        return {"V": 1.0, "mV": 1e-3, "uV": 1e-6}[self.input_units]


def _read_parser(path: str | Path) -> configparser.ConfigParser:
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"SPEED settings file not found: {path}")
    cfg = configparser.ConfigParser(interpolation=None, strict=True, inline_comment_prefixes=(";", "#"))
    cfg.read(path, encoding="utf-8-sig")
    for section in ("source", "channels", "filter", "normalization"):
        if not cfg.has_section(section):
            raise ValueError(f"Missing [{section}] section in {path}")
    if not (cfg.has_section("bridge") or cfg.has_section("game")):
        raise ValueError(f"Missing [bridge] section in {path}")
    return cfg


def read_settings(path: str | Path) -> SpeedSettings:
    cfg = _read_parser(path)
    def txt(section: str, key: str) -> str:
        return cfg.get(section, key).strip()
    def num(section: str, key: str) -> float:
        n = cfg.getfloat(section, key)
        if not math.isfinite(n):
            raise ValueError(f"{section}.{key} must be finite")
        return n
    value = SpeedSettings(
        source_service=txt("source", "service"),
        source_stream=txt("source", "stream"),
        sampling_rate_hz=num("source", "sampling_rate_hz"),
        input_units=txt("source", "input_units"),
        left_channel=cfg.getint("channels", "left_channel"),
        right_channel=cfg.getint("channels", "right_channel"),
        left_sensor_name=txt("channels", "left_sensor_name"),
        right_sensor_name=txt("channels", "right_sensor_name"),
        threshold_mode=txt("normalization", "threshold_mode").lower(),
        left_threshold_uv=num("normalization", "left_threshold_uv"),
        right_threshold_uv=num("normalization", "right_threshold_uv"),
        low_hz=num("filter", "low_hz"),
        high_hz=num("filter", "high_hz"),
        notch_hz=num("filter", "notch_hz"),
        notch_q=num("filter", "notch_q"),
        filter_order=cfg.getint("filter", "order"),
        rms_window_ms=num("filter", "rms_window_ms"),
        attack_ms=num("filter", "attack_ms"),
        release_ms=num("filter", "release_ms"),
        rolling_window_seconds=num("normalization", "rolling_window_seconds"),
        bridge_enabled=cfg.getboolean("bridge" if cfg.has_section("bridge") else "game",
                                      "enabled" if cfg.has_section("bridge") else "udp_enabled"),
        bridge_host=cfg.get("bridge", "host", fallback=cfg.get("game", "udp_host", fallback="127.0.0.1")).strip(),
        bridge_port=cfg.getint("bridge", "port", fallback=cfg.getint("game", "udp_port", fallback=8765)),
        event_detector=ContractionDetectorSettings(
            calibration_seconds=cfg.getfloat("event_detection", "calibration_seconds", fallback=2.0),
            onset_sigma=cfg.getfloat("event_detection", "onset_sigma", fallback=4.0),
            release_sigma=cfg.getfloat("event_detection", "release_sigma", fallback=1.5),
            min_contraction_ms=cfg.getfloat("event_detection", "min_contraction_ms", fallback=20.0),
            release_ms=cfg.getfloat("event_detection", "release_ms", fallback=28.0),
            refractory_ms=cfg.getfloat("event_detection", "refractory_ms", fallback=65.0),
            full_scale_sigma=cfg.getfloat("event_detection", "full_scale_sigma", fallback=14.0),
            baseline_tracking_seconds=cfg.getfloat("event_detection", "baseline_tracking_seconds", fallback=12.0),
            minimum_noise_floor=cfg.getfloat("event_detection", "minimum_noise_floor", fallback=1e-12),
        ),
    )
    validate_settings(value)
    return value


def validate_settings(settings: SpeedSettings) -> None:
    s = settings
    if not s.source_service or not s.source_stream:
        raise ValueError("source.service and source.stream cannot be blank")
    if any(ch in s.source_service + s.source_stream for ch in "&=?\r\n"):
        raise ValueError("source service and stream names cannot contain &, =, ?, or newlines")
    if s.input_units not in ("V", "mV", "uV"):
        raise ValueError("source.input_units must be V, mV or uV")
    if s.sampling_rate_hz <= 0:
        raise ValueError("source.sampling_rate_hz must be > 0")
    if not s.left_sensor_name or not s.right_sensor_name:
        raise ValueError("Channel sensor_name labels cannot be empty")
    if s.left_channel < 0 or s.right_channel < 0:
        raise ValueError("Channel numbers must be positive, or zero when disabled")
    if s.left_channel == 0 and s.right_channel == 0:
        raise ValueError("At least one signal channel must be enabled")
    if s.left_channel != 0 and s.left_channel == s.right_channel:
        raise ValueError("left_channel and right_channel must differ, unless disabled")
    if s.threshold_mode not in ("baseline", "manual"):
        raise ValueError("normalization.threshold_mode must be baseline or manual")
    if s.left_threshold_uv < 0 or s.right_threshold_uv < 0:
        raise ValueError("Manual thresholds must be >= 0")
    if s.rolling_window_seconds <= 0:
        raise ValueError("normalization.rolling_window_seconds must be > 0")
    if not 1 <= s.bridge_port <= 65535:
        raise ValueError("bridge.port must be in [1, 65535]")
    if not s.bridge_host:
        raise ValueError("bridge.host cannot be empty")
    filters = make_filter(s)
    filters.validate(s.sampling_rate_hz)
    # The current quality monitor and adaptive mains cancellation use a 45-55/48-52 Hz band.
    if s.sampling_rate_hz <= 110:
        raise ValueError("This EMG pipeline requires sampling_rate_hz > 110 (50Hz quality bands)")
    make_rolling(s).validate(s.sampling_rate_hz)
    s.event_detector.validate(s.sampling_rate_hz)


def make_filter(s: SpeedSettings) -> FilterConfig:
    return FilterConfig(
        low_hz=s.low_hz,
        high_hz=s.high_hz,
        notch_hz=s.notch_hz if s.notch_hz > 0 else None,
        notch_q=s.notch_q,
        order=s.filter_order,
        rms_window_ms=s.rms_window_ms,
        attack_ms=s.attack_ms,
        release_ms=s.release_ms,
    )


def make_rolling(s: SpeedSettings) -> RollingNormalizerConfig:
    return RollingNormalizerConfig(window_seconds=s.rolling_window_seconds)


def _validate_baseline_mode(s: SpeedSettings, report: dict[str, Any]) -> None:
    channels = report["channels"]
    expected = (int(channels["left"]["channel_index"]) + 1,
                int(channels["right"]["channel_index"]) + 1)
    fs = float(report["sampling_rate_hz"])
    source_filter = FilterConfig.from_dict(report.get("config", {}).get("filter", {}))
    if ((s.left_channel, s.right_channel) != expected
            or not math.isclose(s.sampling_rate_hz, fs, abs_tol=0.01, rel_tol=0)
            or make_filter(s) != source_filter or s.input_units != "V"):
        raise ValueError(
            "threshold_mode=baseline only supports original channels "
            f"{expected[0]}/{expected[1]}, {fs:g} Hz, original filters and input_units=V. "
            "For a different sensor/80th channel, set threshold_mode=manual and "
            "supply thresholds in microvolts. Old calibration cannot be reused."
        )


def _uncalibrated_profile(side: str, position: int, active: bool, label: str) -> ChannelQualityProfile:
    return ChannelQualityProfile(
        side=side,
        channel_name=(label if active else "disabled"),
        channel_index=position - 1 if active else -1,
        baseline_status="uncalibrated",
        task_to_rest_q95_ratio=None,
        mains_fraction_45_55_hz=None,
        interval_q95_cv=None,
        # Allow runtime quality monitor to provide its diagnostic score, but
        # never activate the uncalibrated control gate.
        quality_score=1.0 if active else 0.0,
        control_allowed=False,
        warnings=("New sensor requires separate rest/task calibration",),
    )


def new_interpreter(s: SpeedSettings, baseline_path: str | Path) -> FinalEMGInterpreter:
    report = load_baseline_report(baseline_path)
    rolling = make_rolling(s)
    if s.threshold_mode == "baseline":
        _validate_baseline_mode(s, report)
        processor = FinalEMGInterpreter.from_baseline_report(
            baseline_path, normalizer_config=rolling)
        # The configured streaming interface always selects up to two columns.
        # The calibrated filter/threshold/quality state is otherwise identical.
        processor.adaptive.indices = (0, 1)
        return processor

    adaptive = AdaptiveEMGInterpreter(
        sampling_rate_hz=s.sampling_rate_hz,
        left_channel_index=0,
        right_channel_index=1,
        left_threshold_rms=s.left_threshold_uv * 1e-6,
        right_threshold_rms=s.right_threshold_uv * 1e-6,
        left_quality=_uncalibrated_profile("left", s.left_channel, s.left_channel != 0, s.left_sensor_name),
        right_quality=_uncalibrated_profile("right", s.right_channel, s.right_channel != 0, s.right_sensor_name),
        filter_config=make_filter(s),
        normalizer_config=rolling,
    )
    # Adapt the quality-monitor band to the configured filter while retaining
    # the existing cancellation algorithm and conservative control restrictions.
    monitor = SignalQualityConfig(
        signal_low_hz=s.low_hz, signal_high_hz=s.high_hz,
    )
    mains = MainsCancellerConfig(**report.get("config", {}).get("mains_canceller", {}))
    return FinalEMGInterpreter(adaptive, quality_config=monitor, mains_config=mains)


class ConfiguredSpeedProcessor:
    """Small testable adapter from native channel arrays to the existing algorithm."""
    def __init__(self, settings: SpeedSettings, baseline_path: str | Path):
        self.settings = settings
        self.baseline_path = Path(baseline_path)
        self.interpreter: FinalEMGInterpreter | None = None
        self.publisher: Any = None
        self.detector: ContractionEventDetector | None = None
        self._bridge_error_reported = False
        self._detector_ready_reported = False

    def prepare(self, sampling_rate_hz: float, channel_count: int) -> None:
        s = self.settings
        if not math.isclose(float(sampling_rate_hz), s.sampling_rate_hz, abs_tol=0.05, rel_tol=0):
            raise ValueError(
                f"Input rate {sampling_rate_hz:g} Hz != speed_configurator.txt "
                f"{s.sampling_rate_hz:g} Hz. No automatic resampling."
            )
        required = max(s.left_channel, s.right_channel)
        if channel_count < required:
            raise ValueError(
                f"Input has {channel_count} channels, settings require channel {required} "
                "(channels numbered from 1). Check LSL bridge layout."
            )
        self.interpreter = new_interpreter(s, self.baseline_path)
        self.detector = ContractionEventDetector(
            s.sampling_rate_hz,
            settings=s.event_detector,
            enabled=(s.left_channel != 0, s.right_channel != 0),
        )
        self._bridge_error_reported = False
        self._detector_ready_reported = False
        if self.publisher is not None:
            self.publisher.close()
            self.publisher = None
        if s.bridge_enabled:
            from Bridge.emg_game_bridge import GameBridgePublisher
            self.publisher = GameBridgePublisher(host=s.bridge_host, port=s.bridge_port)
        print(
            "SPEED config: rate={:g}Hz source={}@{} L={} R={} mode={} Bridge={}".format(
                s.sampling_rate_hz, s.source_stream, s.source_service,
                s.left_channel, s.right_channel, s.threshold_mode,
                "enabled" if s.bridge_enabled else "disabled"), flush=True)

    def process(self, matrix: np.ndarray, timestamps_ns: np.ndarray | None):
        if self.interpreter is None:
            raise RuntimeError("SPEED not prepared")
        s = self.settings
        raw = np.asarray(matrix, dtype=np.float64)
        if raw.ndim != 2:
            raise ValueError(f"Expected [samples,channels], got {raw.shape}")
        selected = np.zeros((raw.shape[0], 2), dtype=np.float64)
        for channel, index in enumerate(s.source_indices):
            if index is not None:
                selected[:, channel] = raw[:, index] * s.unit_scale
        frame = self.interpreter.process_block(selected, timestamps_ns)
        # Disabled sides must never generate events, even though the SPEED
        # transform preserves a fixed two-output layout.
        envelope = np.column_stack((frame.left_rms, frame.right_rms))
        valid = np.column_stack((frame.left_control_valid, frame.right_control_valid))
        if self.detector is None:
            raise RuntimeError("Contraction detector was not prepared")
        events, pulses = self.detector.process(
            envelope,
            timestamps_ns=timestamps_ns,
            valid_mask=valid,
        )
        enabled = (s.left_channel != 0, s.right_channel != 0)
        ready = self.detector.ready
        if not self._detector_ready_reported and all(ready[i] or not enabled[i] for i in range(2)):
            baseline_text = ", ".join(
                f"{arm}={value:.3g} V" for arm, value, active in zip(
                    ("left", "right"), self.detector.baselines, enabled
                ) if active and value is not None
            )
            print(
                "QuasiGame contraction detector ready after quiet calibration "
                f"({self.settings.event_detector.calibration_seconds:g}s); baseline RMS: {baseline_text}",
                flush=True,
            )
            self._detector_ready_reported = True
        if self.publisher is not None and events:
            try:
                self.publisher.publish_events(events)
            except Exception as exc:
                if not self._bridge_error_reported:
                    print(f"QuasiGame Bridge error: {exc!r}", flush=True)
                    self._bridge_error_reported = True
        # SPEED output traces now contain isolated event pulses (zero otherwise),
        # not a continuously varying activity level.
        return np.clip(pulses, 0.0, 1.0)


def build_configured_speed(settings_path: str | Path, baseline_path: str | Path) -> None:
    """Register two sparse event streams: left/right contraction pulses.

    Each output is zero between contractions and contains one normalized
    0..1 intensity pulse when a contraction has been confirmed. The Bridge
    sends that event to GameAPI as one discrete contraction message.
    """
    import resonance
    import resonance.db as db
    import resonance.si as si
    from resonance.internal import Processor

    settings = read_settings(settings_path)
    baseline = Path(baseline_path)
    new_interpreter(settings, baseline)

    class _ConfiguredTransform(Processor):
        def __init__(self) -> None:
            self._adapter = ConfiguredSpeedProcessor(settings, baseline)
            self._output_si: tuple[Any, Any] | None = None

        def prepare(self, channels: db.Channels):
            if not isinstance(channels, db.Channels):
                raise TypeError("SPEED expects a numeric Channels stream")
            rate = float(channels.SI.samplingRate)
            count = int(channels.SI.channels)
            self._adapter.prepare(rate, count)
            self._output_si = (
                si.Channels(channels=1, samplingRate=rate),
                si.Channels(channels=1, samplingRate=rate),
            )
            return self._output_si

        def online(self, channels: db.Channels):
            if self._output_si is None:
                raise RuntimeError("Configured SPEED is not prepared")
            strengths = self._adapter.process(np.asarray(channels), channels.TS)
            if strengths.ndim != 2 or strengths.shape[1] != 2:
                raise RuntimeError(f"Expected two contraction-event columns, got {strengths.shape}")
            return tuple(
                db.Channels(output_si, channels.TS, strengths[:, idx:idx + 1])
                for idx, output_si in enumerate(self._output_si)
            )

    left_output, right_output = _ConfiguredTransform().call(resonance.input(0))
    resonance.createOutput(left_output, "left_contraction_event")
    resonance.createOutput(right_output, "right_contraction_event")
